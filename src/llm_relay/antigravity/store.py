def log_quota(conn: Any, *, provider: str, buckets: List[Dict[str, Any]]) -> int:
    """Insert one ``provider_quota`` row per bucket (one shared ts per snapshot). Returns rows inserted.

    Missing keys are stored as NULL; entries without a ``bucket_id`` (missing,
    None or empty) and non-dict entries are skipped.
    """
    from llm_relay.proxy import db

    ts = db._ts_now()
    sql = "INSERT INTO provider_quota (ts, provider, {}) VALUES ({})".format(
        ", ".join(_QUOTA_FIELDS), ", ".join(["?"] * (len(_QUOTA_FIELDS) + 2)))
    inserted = 0
    for bucket in buckets or ():
        if not isinstance(bucket, dict) or not bucket.get("bucket_id"):
            continue
        conn.execute(sql, (ts, provider) + tuple(bucket.get(field) for field in _QUOTA_FIELDS))
        inserted += 1
    if inserted:
        conn.commit()
    return inserted


def get_last_turn_state(conn: Any, provider: str, session_id: str) -> Optional[Dict[str, Any]]:
    """Newest stored turn of a provider session by (turn_number, id), or None.

    Returns ``{"turn_number", "total_message_count", "first_fingerprint"}`` so a
    restarted relay continues the turn numbering and the delta of a session.
    """
    row = conn.execute(
        "SELECT turn_number, total_message_count, first_fingerprint FROM provider_turns"
        " WHERE provider = ? AND session_id = ? ORDER BY turn_number DESC, id DESC LIMIT 1",
        (provider, session_id),
    ).fetchone()
    if not row:
        return None
    return {
        "turn_number": int(row["turn_number"]),
        "total_message_count": int(row["total_message_count"] or 0),
        "first_fingerprint": row["first_fingerprint"],
    }


def get_latest_quota(conn: Any, provider: str) -> List[Dict[str, Any]]:
    """Newest ``provider_quota`` row per ``bucket_id`` of a provider (by ts, then id), ordered by bucket_id.

    Plain dicts with every column; ``ts`` is returned as stored (epoch float on
    SQLite, datetime on PostgreSQL).
    """
    rows = conn.execute(
        "SELECT id, ts, provider, group_name, bucket_id, quota_window, remaining_fraction, reset_time,"
        " display_name FROM (SELECT q.*, ROW_NUMBER() OVER (PARTITION BY bucket_id ORDER BY ts DESC, id DESC)"
        " AS rn FROM provider_quota q WHERE provider = ?) latest WHERE rn = 1 ORDER BY bucket_id",
        (provider,),
    ).fetchall()
    return [dict(row) for row in rows]
