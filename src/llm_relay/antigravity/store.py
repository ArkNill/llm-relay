"""Storage for non-Claude-Code provider traffic (Antigravity CLI) in dedicated ``provider_*`` tables.

The Claude Code proxy owns ``requests`` and ``conversation_turns``; statistics,
usage meters and the embedding pipeline read them. This module never names
those tables: everything it creates, writes or reads is one of ``ALL_TABLES``,
and every row carries a ``provider`` tag (e.g. ``"antigravity-cli"``).

``TABLES`` are the three tables capture cannot work without. ``OPTIONAL_TABLES``
(``provider_blobs``) and the ``NEW_REQUEST_COLUMNS`` of ``provider_requests``
came later: a database migrated before them keeps capturing, with the rows
written to the columns that exist (``request_columns_present`` and
``log_request(available_columns=...)``).

Backends follow ``llm_relay.proxy.db``: SQLite gets its schema from
``ensure_schema`` (``SQLITE_SCHEMA`` plus ``ALTER TABLE ... ADD COLUMN`` for
columns an older file lacks; safe to run repeatedly); the PostgreSQL schema is
managed outside the relay, so ``PG_DDL`` / ``column_defs`` are applied by the
migration scripts under ``docs/`` and ``ensure_schema`` does nothing there.
The ``log_*`` functions do not create tables or catch a missing-table error;
callers check ``tables_present`` first.

``llm_relay.proxy.db`` loads the repo's env files at import time (which may
point at the production database), so it is imported lazily inside the
functions that need its value adapters. Importing this module opens no
connection and reads no environment, which lets the migration script import
``PG_DDL`` and ``TABLES`` without side effects.
"""

