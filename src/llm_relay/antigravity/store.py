_DIALECT_TYPE_INDEX = {"sqlite": 1, "pg": 2}

# (index, table, columns) -- the same definitions on both backends.
# ensure_schema runs these before it adds missing columns to an older SQLite file, so an index
# may only name columns that table had from the start (the old-schema upgrade test catches it).
INDEXES: Tuple[Tuple[str, str, Tuple[str, ...]], ...] = (
    ("idx_provider_requests_ts", "provider_requests", ("ts",)),
    ("idx_provider_requests_session", "provider_requests", ("provider", "session_id", "ts")),
    ("idx_provider_turns_session", "provider_turns", ("provider", "session_id", "turn_number")),
    ("idx_provider_turns_ts", "provider_turns", ("ts",)),
    ("idx_provider_quota_bucket", "provider_quota", ("provider", "bucket_id", "ts")),
    ("idx_provider_blobs_key", "provider_blobs", ("provider", "kind", "sha256")),
)
# log_blob's ON CONFLICT / INSERT OR IGNORE depend on this one being unique.
UNIQUE_INDEXES = frozenset({"idx_provider_blobs_key"})


def column_defs(table: str, dialect: str) -> List[Tuple[str, str]]:
    """(column, type) of one of ``ALL_TABLES`` in table order; ``dialect`` is ``"sqlite"`` or ``"pg"``."""
    if dialect not in _DIALECT_TYPE_INDEX:
        raise ValueError("dialect must be 'sqlite' or 'pg'")
    type_index = _DIALECT_TYPE_INDEX[dialect]
    return [(col[0], col[type_index]) for col in _COLUMNS[table]]


def _create_table(table: str, type_index: int) -> str:
    cols = ",\n".join("    {} {}".format(col[0], col[type_index]) for col in _COLUMNS[table])
    return "CREATE TABLE IF NOT EXISTS {} (\n{}\n)".format(table, cols)


def _create_index(name: str, table: str, columns: Tuple[str, ...]) -> str:
    unique = "UNIQUE " if name in UNIQUE_INDEXES else ""
    return "CREATE {}INDEX IF NOT EXISTS {} ON {} ({})".format(unique, name, table, ", ".join(columns))


def _ddl(type_index: int) -> List[str]:
    statements = [_create_table(table, type_index) for table in ALL_TABLES]
    statements.extend(_create_index(*index) for index in INDEXES)
    return statements


SQLITE_SCHEMA: str = ";\n\n".join(_ddl(1)) + ";\n"

# One statement per element: the migration script runs them one by one in autocommit.
# Plain CREATE INDEX (not CONCURRENTLY) is fine because it only ever locks a new provider_* table.
PG_DDL: List[str] = _ddl(2)

_QUOTA_FIELDS = ("group_name", "bucket_id", "quota_window", "remaining_fraction", "reset_time", "display_name")
_REPLACEMENT = "\ufffd"  # REPLACEMENT CHARACTER, stands in for NUL and lone surrogates
# Characters PostgreSQL refuses: NUL (jsonb and text) and any UTF-16 surrogate code point.
# json.loads joins a valid surrogate pair into one astral character, so whatever is left
# in a Python str in U+D800..U+DFFF is unpaired and has no UTF-8 encoding.
_PG_REJECTED_CHARS = re.compile(r"[\x00\ud800-\udfff]")


def _is_sqlite(conn: Any) -> bool:
    """SQL dialect by connection type: anything that is not sqlite3 is the PostgreSQL wrapper."""
    return isinstance(conn, sqlite3.Connection)


def ensure_schema(conn: Any) -> None:
    """Create the provider tables and indexes on SQLite and add missing columns (idempotent); no-op on PostgreSQL.

    ``CREATE TABLE IF NOT EXISTS`` leaves a table from an older release as it
    is, so every column of ``_COLUMNS`` it lacks is added afterwards with
    ``ALTER TABLE ... ADD COLUMN`` (existing rows keep their values; the new
    columns read NULL or their DEFAULT).
    """
    if not _is_sqlite(conn):
        return
    conn.executescript(SQLITE_SCHEMA)
    for table in ALL_TABLES:
        present = _sqlite_columns(conn, table)
        for name, sql_type in column_defs(table, "sqlite"):
            if name not in present:
                # Names and types come from _COLUMNS, never from input.
                conn.execute("ALTER TABLE {} ADD COLUMN {} {}".format(table, name, sql_type))
    conn.commit()


def tables_present(conn: Any, tables: Tuple[str, ...] = TABLES) -> Dict[str, bool]:
    """Which of ``tables`` (default: the required ``TABLES``) exist.

    SQLite: sqlite_master; PostgreSQL: the current schema. Read-only.
    """
    if not tables:
        return {}
    if _is_sqlite(conn):
        sql = "SELECT name AS table_name FROM sqlite_master WHERE type = 'table' AND name IN ({})"
        placeholder = "?"
    else:
        # %s works on the _PGWrapper (it only rewrites "?") and on a bare psycopg connection.
        sql = ("SELECT table_name FROM information_schema.tables"
               " WHERE table_schema = current_schema() AND table_name IN ({})")
        placeholder = "%s"
    rows = conn.execute(sql.format(", ".join([placeholder] * len(tables))), tuple(tables)).fetchall()
    found = {row["table_name"] for row in rows}
    return {table: table in found for table in tables}


def _sqlite_columns(conn: Any, table: str) -> Set[str]:
    """Column names of a SQLite table; empty when it does not exist. ``table`` is one of ours."""
    # row[1] = name; by position so that a connection without sqlite3.Row works too.
    return {row[1] for row in conn.execute("PRAGMA table_info({})".format(table)).fetchall()}


def request_columns_present(conn: Any) -> Set[str]:
    """Column names ``provider_requests`` has now; empty when the table is missing. Read-only.

    SQLite: ``PRAGMA table_info``; PostgreSQL: ``information_schema.columns`` of
    the current schema. ``log_request(available_columns=...)`` takes the result.
    """
    if _is_sqlite(conn):
        return _sqlite_columns(conn, "provider_requests")
    # No parameters: the table name is a literal, so the SQL holds neither "?" nor "%".
    rows = conn.execute(
        "SELECT column_name FROM information_schema.columns"
        " WHERE table_schema = current_schema() AND table_name = 'provider_requests'"
    ).fetchall()
    return {row["column_name"] for row in rows}


def strip_nul(value: Any) -> Any:
    """Replace the values PostgreSQL rejects, recursively, dict keys included.

    - strings: every NUL and every surrogate code point (U+D800..U+DFFF) becomes
      ``"\\ufffd"``. ``jsonb`` rejects the ``\\u0000`` escape and unpaired
      surrogates, ``text`` rejects NUL, and the client cannot encode a lone
      surrogate as UTF-8 at all (2026-10: about 660 conversation turns were lost
      to NUL alone). A string without such characters is returned as is.
    - non-finite floats (``json.loads`` gives them for ``NaN`` and ``1e400``):
      ``jsonb`` has no such numbers, so they become the strings ``"NaN"``,
      ``"Infinity"`` and ``"-Infinity"``. bool, int and finite floats stay.

    Containers are rebuilt (list, tuple, dict keep their type); any other value
    is returned unchanged. The name predates the surrogate and float cases and is
    kept for the callers.
    """
    if isinstance(value, str):
        return _PG_REJECTED_CHARS.sub(_REPLACEMENT, value) if _PG_REJECTED_CHARS.search(value) else value
    if isinstance(value, float):
        if math.isnan(value):
            return "NaN"
        if math.isinf(value):
            return "Infinity" if value > 0 else "-Infinity"
        return value
    if isinstance(value, dict):
        return {strip_nul(k): strip_nul(v) for k, v in value.items()}
    if isinstance(value, list):
        return [strip_nul(v) for v in value]
    if isinstance(value, tuple):
        return tuple(strip_nul(v) for v in value)
    return value


def _insert(conn: Any, table: str, values: Dict[str, Any]) -> int:
    """INSERT one row and return its id (``RETURNING id`` on PostgreSQL, ``lastrowid`` on SQLite)."""
    columns = list(values)
    sql = "INSERT INTO {} ({}) VALUES ({})".format(table, ", ".join(columns), ", ".join(["?"] * len(columns)))
    # Every plain string goes through strip_nul, not only the JSON columns: PostgreSQL
    # rejects NUL in TEXT as well, and one bad id must not cost the whole row.
    params = tuple(strip_nul(values[col]) if isinstance(values[col], str) else values[col] for col in columns)
    if _is_sqlite(conn):
        cursor = conn.execute(sql, params)
        conn.commit()
        return cursor.lastrowid or 0
    cursor = conn.execute(sql + " RETURNING id", params)
    row = cursor.fetchone()
    conn.commit()
    return row["id"] if row else 0


